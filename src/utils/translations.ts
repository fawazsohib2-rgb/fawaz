// Helper to format numbers (e.g. 123 -> ١٢٣ if arabicNumerals is true)
export function formatNum(num: number | string, useArabicNumerals: boolean): string {
  const str = String(num);
  if (!useArabicNumerals) return str;
  const arabicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return str.replace(/\d/g, (d) => arabicDigits[parseInt(d, 10)]);
}

// Localized string helper with fallback to English
export function getLoc(obj: LocalizedString | undefined, lang: Language): string {
  if (!obj) return '';
  return obj[lang] || obj.en || obj.ar || '';
}

// Localized string array helper with fallback to English
export function getLocArr(obj: LocalizedStringArray | undefined, lang: Language): string[] {
  if (!obj) return [];
  return obj[lang] || obj.en || obj.ar || [];
}
